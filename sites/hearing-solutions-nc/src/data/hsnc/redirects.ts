/**
 * Old paths that only redirect WITH the trailing slash, because the bare path is a page on
 * the new site (the site ignores trailing slashes, so these win over the new page's slash form).
 */
export const SLASH_ONLY: Record<string, string> = {
	// Empty: nothing on the new site needs this any more.
};

/** The new location for an old URL path, or undefined. The query string is passed on by the caller. */
export function redirectFor(pathname: string): string | undefined {
	let p = pathname.toLowerCase();
	try {
		p = decodeURI(p);
	} catch {
		/* keep it encoded */
	}
	if (SLASH_ONLY[p]) return SLASH_ONLY[p];
	const bare = p.replace(/\/+$/, "");
	const kept = bare.startsWith("/patient-resources/") ? RESOURCE_PATHS[bare.slice("/patient-resources/".length)] : undefined;
	return kept ?? REDIRECTS[bare];
}

/** A 301 to the new location, keeping the query string (before any #section). */
export function redirectResponse(to: string, search: string): Response {
	const [path, hash] = to.split("#");
	const location = path + (search || "") + (hash ? `#${hash}` : "");
	return new Response(null, { status: 301, headers: { Location: location } });
}
