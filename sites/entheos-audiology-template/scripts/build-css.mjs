// Builds src/styles/d1.css from the design's stylesheet (design/styles/d1.css).
//
// The design boards draw phones inside a `.m` wrapper, so every mobile rule in
// the source is written as `.m .thing{...}`. On a real site there is no wrapper:
// mobile is a screen width. This script moves each `.m` rule into
// `@media (max-width: 1023px)` and swaps `.m` for `.d1` (the class on <body>),
// which keeps each selector's specificity exactly as the designer had it.
//
// design/styles/d1.css stays the single source. Edit it there, not the output.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("..", import.meta.url));
const src = readFileSync(root + "design/styles/d1.css", "utf8");

const MOBILE = "@media (max-width: 1023px)";

// Split into top-level blocks: plain rules, and at-rules with nested braces.
function topLevelBlocks(css) {
	const out = [];
	let i = 0;
	while (i < css.length) {
		const open = css.indexOf("{", i);
		if (open === -1) break;
		let depth = 0;
		let j = open;
		for (; j < css.length; j++) {
			if (css[j] === "{") depth++;
			else if (css[j] === "}" && --depth === 0) break;
		}
		const prelude = css.slice(i, open);
		// keep any comment that sits before the selector with the desktop output
		const comments = prelude.match(/\/\*[\s\S]*?\*\//g) ?? [];
		const selector = prelude.replace(/\/\*[\s\S]*?\*\//g, "").trim();
		out.push({ comments, selector, body: css.slice(open + 1, j) });
		i = j + 1;
	}
	return out;
}

const isMobileSelector = (sel) =>
	sel.split(",").every((s) => /^\.m(\s|$)/.test(s.trim()));

const desktop = [];
const mobile = [];
let moved = 0;

for (const b of topLevelBlocks(src)) {
	desktop.push(...b.comments);
	if (b.selector.startsWith("@")) {
		desktop.push(`${b.selector}{${b.body}}`);
		continue;
	}
	if (isMobileSelector(b.selector)) {
		const sel = b.selector
			.split(",")
			.map((s) => s.trim().replace(/^\.m(?=\s|$)/, ".d1"))
			.join(",");
		mobile.push(`${sel}{${b.body}}`);
		moved++;
		continue;
	}
	if (b.selector.split(",").some((s) => /(^|\s)\.m(\s|$)/.test(s))) {
		throw new Error(`Mixed .m selector list, split it in the source: ${b.selector}`);
	}
	desktop.push(`${b.selector}{${b.body}}`);
}

const out = `/* GENERATED by scripts/build-css.mjs from design/styles/d1.css. Do not edit. */
${desktop.join("\n")}

/* ---------- mobile (the design's .m rules) ---------- */
${MOBILE}{
${mobile.join("\n")}
}
`;

writeFileSync(root + "src/styles/d1.css", out);
console.log(`d1.css: ${moved} mobile rules moved into ${MOBILE}`);
