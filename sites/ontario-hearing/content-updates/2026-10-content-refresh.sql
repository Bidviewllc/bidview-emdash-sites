Ringing is the most common description, and tinnitus also sounds like buzzing, roaring, clicking, hissing, humming, or whooshing. Some people hear a pulse that keeps time with their heartbeat. The pitch runs from a low roar to a high squeal, and you can hear it in one ear or both. Other people usually cannot hear it.

## How long the first signs last

Tinnitus can be constant or come and go. Loud sounds can also cause short-term ringing and permanent hearing loss. If the ringing does not fade, or keeps coming back, get it checked.

## Hearing changes that come with early tinnitus

Tinnitus often comes with hearing loss. About 9 in 10 people with tinnitus have some hearing loss, and a hearing test shows whether you do. Some people also notice a feeling of fullness in the ear.

## Effects on sleep, focus, and mood

Tinnitus can make it harder to sleep and focus, and it can affect memory and mood. Quiet rooms make it easier to notice, and stress and anxiety make it feel louder.

## Who is more likely to get tinnitus?

Common risk factors are loud noise exposure and age. Men are more likely to have tinnitus. Smoking, drinking alcohol, high blood pressure and other heart and blood vessel conditions, and a history of head injury also raise the risk.

Some medicines, including high doses of aspirin and some antibiotics, can cause it. Earwax or another blockage in the ear canal can also cause it.

## When to get checked right away

See a doctor right away if tinnitus comes with sudden hearing loss, dizziness, or numbness or weakness in the face, arm, or leg. Get a prompt evaluation for any of these:

- Ringing in one ear only
- A sound that pulses with your heartbeat
- Ringing after a head injury or accident
- Ringing that follows a cold and has not improved in a week
- Anxiety, depression, or lost sleep from tinnitus

Ringing in one ear with a drop in hearing can be sudden sensorineural hearing loss, and treatment can be time sensitive. Audiologists and ENT doctors work together on tinnitus.

## What happens at a tinnitus evaluation?

A tinnitus evaluation starts with a comprehensive hearing test and questions about your tinnitus: when you notice it, what it sounds like, how loud it is, what makes it worse, and whether it affects your sleep or concentration. The [2026 clinical guideline](https://www.newswise.com/articles/living-with-ringing-in-your-ears-updated-guideline-supports-a-personalized-evidence-based-approach-to-tinnitus) from the American Academy of Otolaryngology-Head and Neck Surgery Foundation says every patient with tinnitus should have a comprehensive hearing evaluation.

A doctor will also ask about your history and examine your ears, head, and neck. Scans are limited to people with specific concerning features. Every patient at Ontario Hearing Center is seen by a doctoral-level audiologist. If everyday sounds also feel painfully loud, we evaluate sound sensitivity, called hyperacusis.

