## Phonak Audéo EON Line

The Phonak Audéo EON Line is Phonak''s newest generation of hearing technology, with clearer speech, longer battery life, and a smaller, lighter design. Released in August 2026, EON replaces the Infinio Ultra line. It runs on the new HYPERSONIC™ chip, which pairs real-time AI sound processing with better power efficiency.

Because EON is built on a new chip, it is new hardware rather than a firmware update. Current Infinio or Infinio Ultra users need new devices to get EON''s features. All EON models are rechargeable and connect to almost any Bluetooth device, with Auracast™ broadcast audio support built in.

### Audéo EON R

A versatile, everyday model powered by AutoSense OS™ AI 8.0, which automatically adjusts to changing sound environments. It suits patients with mild to profound hearing loss who want reliable, hands-free performance in daily listening.

### Audéo EON Sphere

The top of the EON range, built for noisy, complex situations. It features Spheric Speech Clarity 3.0, which separates speech from background noise in real time so voices stand out. It is also the smallest device on the EON platform and suits mild to profound hearing loss.

### CROS EON R

The CROS EON R is designed for single-sided hearing loss. It picks up sound on the side with poorer hearing and sends it to the better ear, so patients no longer miss conversations on one side.

**Unique Features:**

- HYPERSONIC™ chip uses 37% less power than the previous generation while keeping full real-time AI performance.
- The EON Sphere is 25% smaller and 20% lighter than the previous Sphere generation, making it more comfortable with glasses or smaller ears.
- Made-For-All connectivity pairs with virtually any Bluetooth device, and Auracast support lets wearers stream audio directly in venues that broadcast it.

