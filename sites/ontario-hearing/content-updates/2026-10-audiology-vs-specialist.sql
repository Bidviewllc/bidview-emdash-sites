## What to expect at each type of appointment

A [hearing test](/hearing-test/) is the starting point. You listen to tones and repeat words, we look in your ears, and you leave with an audiogram and a plain-English explanation of what it shows.

A [hearing aid fitting](/hearing-aid-fittings-in-rochester-ny/) is a separate visit. Your audiologist programs the devices to your own results, then verifies what they deliver in your ears using [real ear measurement](/real-ear-measurement/) rather than manufacturer defaults.

A [tinnitus](/tinnitus/) appointment starts with a hearing evaluation, because hearing loss sits behind a large share of tinnitus cases, then moves to the management options that suit what the testing shows.

Follow-up visits are where the fine-tuning happens, once you have worn the devices in your own kitchen, your own car and your own restaurants.

