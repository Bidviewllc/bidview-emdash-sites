## ReSound Sensia

ReSound Sensia is ReSound''s newest premium hearing aid family. It was released in August 2026 and built on GN''s new AI platform. Its Intelligent All-Around technology combines a real-time sound classifier, a 4-microphone beamformer, and Deep Neural Network noise reduction to lift the voice you want to hear, not just the loudest one in the room. It works automatically, and wearers can focus on a speaker simply by facing them.

Sensia comes in microRIE, RIE, and custom in-ear styles, including rechargeable options. A Bimodal version works with Cochlear™ Nucleus® implant sound processors. ReSound calls Sensia the **world''s smallest AI hearing aid**.

